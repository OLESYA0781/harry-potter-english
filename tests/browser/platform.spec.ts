import { test, expect } from '@playwright/test';
const fixture = '/tests/fixtures/platform.html';
test('root opens classroom; trial resumes old answers and all twelve remaining chapters', async ({ page }) => {
  await page.addInitScript(() => {
    if (!localStorage.getItem('hogwarts-english-v1')) localStorage.setItem('hogwarts-english-v1', JSON.stringify({ version: 3, data: { step: 7, name: 'Вика', answers: { grammar0: 2 }, scores: { grammar0: { correct: true, first: false, latest: true, skill: 'Grammar' } }, ratings: { reading: 2 } } }));
  });
  await page.goto('/');
  await expect(page.getByRole('heading', { name: 'My Lessons', level: 1 })).toBeVisible();
  await expect(page.getByRole('heading', { name: 'My Lessons' })).toBeVisible();
  await expect(page.locator('.heading-translation')).toHaveText('Мои занятия');
  await expect(page.getByText(/Завершено:/)).toHaveCount(0);
  await expect(page.locator('.platform-brand small')).toHaveCount(0);
  await expect(page.getByRole('heading', { name: 'Trial Lesson', exact: true })).toBeVisible();
  await expect(page.locator('.lesson-card').filter({has:page.getByRole('heading',{name:'Trial Lesson',exact:true})}).locator('.lesson-subtitle')).toHaveText('Пробное занятие');
  await expect(page.getByText('В процессе', { exact: true })).toHaveCount(0);
  await expect(page.locator('.classroom-home')).not.toContainText('Welcome to your English Adventure!');
  await expect(page.locator('.classroom-home')).not.toContainText('YOUR MAGICAL CLASSROOM');
  await expect(page.locator('.classroom-home .castle-art')).toBeVisible();
  await expect(page.locator('.classroom-home')).not.toContainText('Little steps. Big magic.');
  await expect(page.locator('.classroom-home')).not.toContainText('Привет');
  await expect(page.locator('.classroom-home')).not.toContainText('Немного смелости');
  await expect(page.locator('.classroom-home')).not.toContainText('Учись в своём темпе');
  await expect(page.locator('.classroom-home')).not.toContainText('Каждая попытка');
  await expect(page.locator('.classroom-home')).not.toContainText('YOUR NEXT CHAPTER');
  await expect(page.locator('.classroom-home')).not.toContainText('Твоё путешествие продолжается');
  await expect(page.getByLabel('Выбери своё приключение').locator('option')).toHaveText(['Lesson 1 — Present Simple · Ещё не начат', 'Lesson 0 — To Be · Ещё не начат', 'Trial Lesson']);
  await expect(page.locator('.lesson-card h3')).toHaveText(['Lesson 1 — Present Simple','Lesson 0 — To Be','Trial Lesson']);
  await page.getByText('Lessons',{exact:true}).click();
  await expect(page.locator('.lesson-menu:not(.homework-menu) li strong')).toHaveText(['Lesson 1 — Present Simple','Lesson 0 — To Be','Trial Lesson']);
  await page.getByText('Lessons',{exact:true}).click();
  await page.getByLabel('Выбери своё приключение').selectOption('trial');
  await page.getByRole('button', { name: 'Продолжить урок', exact: true }).click();
  await expect(page.locator('.section-heading h1')).toHaveText('Grammar spells');
  await expect(page.locator('.nav-item')).toHaveCount(12);
  await page.getByRole('link', { name: 'Main Menu', exact: true }).click();
  await expect(page.getByRole('heading', { name: 'My Lessons' })).toBeVisible();
  await page.getByRole('button', { name: 'Продолжить урок', exact: true }).click();
  await expect(page.locator('.section-heading h1')).toHaveText('Grammar spells');
  const state = await page.evaluate(() => JSON.parse(localStorage.getItem('hogwarts-english-v1')!).data);
  expect(state.scores.grammar0).toEqual({ correct: true, first: false, latest: true, skill: 'Grammar' });
  expect(state.ratings.reading).toBe(2);
});

test('registry adds new lessons to both menus in newest-first order; drafts and resets stay isolated', async ({ page }) => {
  await page.goto(fixture);
  const select = page.getByLabel('Выбери своё приключение');
  await expect(select.locator('option')).toHaveText(['Волшебное чтение · Ещё не начат', 'Слова и открытия · Ещё не начат', 'Trial Lesson · Ещё не начат']);
  await page.getByText('Lessons', { exact: true }).click();
  await expect(page.locator('.lesson-menu:not(.homework-menu) li strong')).toHaveText(['Волшебное чтение', 'Слова и открытия', 'Trial Lesson']);
  await page.locator('.lesson-menu:not(.homework-menu)').getByRole('link', { name: /Слова и открытия/ }).click();
  await page.getByLabel('Ответ нового урока').fill('word draft');
  await page.getByRole('button', { name: 'Проверить новый урок' }).click();
  await page.getByText('Lessons', { exact: true }).click();
  await page.locator('.lesson-menu:not(.homework-menu)').getByRole('link', { name: /Волшебное чтение/ }).click();
  await expect(page.getByLabel('Ответ нового урока')).toHaveValue('');
  await page.getByLabel('Ответ нового урока').fill('reading draft');
  await page.getByText('Lessons', { exact: true }).click();
  await page.locator('.lesson-menu:not(.homework-menu)').getByRole('link', { name: /Пробное занятие/ }).click();
  await page.getByRole('button', { name: 'Start our adventure!' }).click();
  await page.getByPlaceholder('Your name', { exact: true }).fill('Вика');
  await page.getByRole('button', { name: 'Restart', exact: true }).click();
  await page.getByRole('button', { name: 'Restart lesson', exact: true }).click();
  await page.getByRole('link', { name: 'Main Menu', exact: true }).click();
  await expect(page.locator('.lesson-card').filter({ hasText: 'Слова и открытия' })).toContainText('Завершён');
  await select.selectOption('word-quest');
  await page.getByRole('button', { name: 'Продолжить урок', exact: true }).click();
  await expect(page.getByLabel('Ответ нового урока')).toHaveValue('word draft');
  await page.getByRole('button', { name: 'Сбросить этот урок' }).click();
  await page.reload();
  await expect(page.getByLabel('Ответ нового урока')).toHaveValue('');
  await page.getByText('Lessons', { exact: true }).click();
  await page.locator('.lesson-menu:not(.homework-menu)').getByRole('link', { name: /Волшебное чтение/ }).click();
  await expect(page.getByLabel('Ответ нового урока')).toHaveValue('reading draft');
});

for (const width of [390, 768, 1280]) test(`classroom and menu fit ${width}px and stay available inside lessons`, async ({ page }) => {
  await page.setViewportSize({ width, height: 900 }); await page.goto('/');
  await expect(page.getByRole('heading', { name: 'My Lessons', level: 1 })).toBeVisible();
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true);
  await page.screenshot({ path: `work/platform-home-${width}.png`, fullPage: true });
  await page.getByText('Lessons', { exact: true }).click();
  await page.locator('.lesson-menu:not(.homework-menu)').getByRole('link', { name: /Пробное занятие/ }).click();
  await page.evaluate(() => window.scrollTo(0, document.body.scrollHeight));
  await expect(page.getByText('Lessons', { exact: true })).toBeInViewport();
  await page.getByRole('link', { name: 'Main Menu', exact: true }).click();
  await expect(page.getByRole('heading', { name: 'My Lessons' })).toBeVisible();
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true);
});
